"""
מאגר ההערכה: הערות חופשיות והכלל שהיה צריך לצאת מכל אחת.

כל דוגמה:
  text      - הטקסט בדיוק כמו שהמערכת מקבלת אותו (שם המורה והבקשה)
  expected  - הכלל הנכון, בצורה אחידה:
              matched  האם יש כלל מתאים
              kind     סוג הכלל
              teachers רשימת מורות (ממוינת)
              days     ימים: 0=ראשון ... 5=שישי
              periods  שעות: 0=שעה ראשונה ... 6=שביעית

הדוגמאות כוללות גם בקשות שאין להן כלל (תודה, העדפות שהפותר לא מכיר):
המודל צריך להחזיר matched=False ולא לנחש.
"""


def _rule(kind, teachers, days=(), periods=()):
    return {"matched": True, "kind": kind, "teachers": sorted(teachers),
            "days": sorted(days), "periods": sorted(periods)}


NO_RULE = {"matched": False, "kind": None, "teachers": [], "days": [], "periods": []}

EXAMPLES = [
    # --- יום חופשי ---
    ("גולדשמידט יהודית - יום ראשון חופשי.",
     _rule("free_day", ["גולדשמידט יהודית"], days=[0])),
    ("קנובלוך רבקה - ללא יום שישי.",
     _rule("free_day", ["קנובלוך רבקה"], days=[5])),
    ("רייכמן חוה - ללא ימי שלישי.",
     _rule("free_day", ["רייכמן חוה"], days=[2])),

    # --- סיום עד שעה ---
    ("טורק שרה - ביום חמישי לסיים עד 12:15.",
     _rule("teacher_end_by", ["טורק שרה"], days=[4], periods=[4])),
    ("אייזנברג דבורה: ביום רביעי אני חייבת לצאת ב-11:15",
     _rule("teacher_end_by", ["אייזנברג דבורה"], days=[3], periods=[3])),

    # --- התחלה משעה ---
    ("הלר מרים - ביום שלישי להתחיל רק מהשעה השלישית.",
     _rule("teacher_start_from", ["הלר מרים"], days=[2], periods=[2])),
    ("בוקסבוים מינדי: ביום שני אפשר רק מ-11:30",
     _rule("teacher_start_from", ["בוקסבוים מינדי"], days=[1], periods=[4])),

    # --- לא בשעות מסוימות ---
    ("שוורץ פערל - ביום שני בלי שעה ראשונה.",
     _rule("teacher_not_periods", ["שוורץ פערל"], days=[1], periods=[0])),
    ("ווגל גאולה - לא לשבץ בשעה השביעית.",
     _rule("teacher_not_periods", ["ווגל גאולה"], periods=[6])),
    ("ארליך חנה: בלי שעה ראשונה וגם בלי שעה שביעית",
     _rule("teacher_not_periods", ["ארליך חנה"], periods=[0, 6])),
    ("סגניות: פריד, בלוך ובעיקר ה. קלוגר - לא לשבץ שעה ראשונה.",
     _rule("teacher_not_periods", ["פריד נחמה", "בלוך מלכה", "קלוגר הודיה"], periods=[0])),

    # --- הערה מעורבת: נימוס + בקשה ---
    ("תודה רבה! ובבקשה יום שלישי חופשי לבילא אדר.",
     _rule("free_day", ["אדר בילא"], days=[2])),

    # --- אין כלל מתאים: המודל צריך לומר "לא מצאתי" ---
    ("תודה רבה על ההתחשבות בשנים הקודמות!", NO_RULE),
    ("זילברמן עדינה: אשמח ללמד שני שיעורים רצופים באותה כיתה", NO_RULE),
    ("יפה חנה: אני מעדיפה ללמד בקומה הראשונה", NO_RULE),
    ("ביום ראשון אני לא יכולה", NO_RULE),   # אין שם מורה: אי אפשר לדעת על מי מדובר
]
